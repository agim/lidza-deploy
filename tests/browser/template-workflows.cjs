const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { mockConsole } = require('./fixtures/console.cjs');
const base = process.env.TEST_WEB_URL || 'http://127.0.0.1:8880';
const go = async (page, route) => { await page.goto(`${base}/console.html#${route}`); await page.locator('#main-content h1').waitFor(); };
(async () => {
 const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
 try {
  for (const width of [390, 1440]) {
   const page = await browser.newPage({ viewport: { width, height: 900 } }), errors = [];
   page.on('pageerror', e => errors.push(e.message));
   page.on('dialog', d => { errors.push('Unexpected native popup'); void d.dismiss(); });
   const state = await mockConsole(page);
   await go(page, 'new-application');
   await page.getByRole('button', { name: 'Continue', exact: true }).click();
   assert.equal(await page.locator('[data-step="0"]').isVisible(), true, 'Invalid source advanced the wizard');
   await page.getByRole('button', { name: 'Browse', exact: true }).click();
   await page.getByRole('button', { name: 'acme/portal Private · main' }).click();
   await page.locator('[name=id]').fill('new-portal');
   await page.getByRole('switch', { name: 'Deploy automatically on branch pushes' }).click();
   await page.waitForFunction(() => getComputedStyle(document.querySelector('[aria-label="Deploy automatically on branch pushes"]')).backgroundColor === 'rgb(57, 255, 136)');
   assert.equal(await page.getByRole('switch', { name: 'Deploy automatically on branch pushes' }).evaluate(e => getComputedStyle(e).backgroundColor), 'rgb(57, 255, 136)');
   await page.getByRole('button', { name: 'Continue', exact: true }).click();
   await page.locator('[name=domain]').fill('new.example.com');
   await page.locator('[name=database_mode]').selectOption('external');
   await page.locator('[name=database_url]').fill('postgres://fixture.example/db?sslmode=require');
   await page.locator('[name=backup_keep]').fill('9');
   await page.locator('[name=backup_offsite]').check();
   await page.getByRole('switch', { name: 'Serve approved customer hostnames' }).click();
   await page.getByRole('button', { name: 'Continue', exact: true }).click();
   await page.getByRole('button', { name: 'Add variable', exact: true }).click();
   await page.getByRole('textbox', { name: 'Variable name', exact: true }).fill('MAIL_API_KEY');
   await page.locator('input[aria-label="Variable value"]').fill('fixture-only-secret');
   await page.getByRole('button', { name: 'Back', exact: true }).click();
   assert.equal(await page.locator('[name=database_url]').inputValue(), 'postgres://fixture.example/db?sslmode=require');
   await page.getByRole('button', { name: 'Continue', exact: true }).click();
   assert.equal(await page.locator('input[aria-label="Variable value"]').inputValue(), 'fixture-only-secret');
   assert.equal(state.calls.filter(c => c.path === 'control/apps' && c.method === 'POST').length, 0, 'Wizard created before final confirmation');
   await page.getByRole('button', { name: 'Create application', exact: true }).click();
   await page.waitForURL(url => url.hash === '#applications');
   const created = state.calls.find(c => c.path === 'control/apps' && c.method === 'POST').body;
   assert.equal(created.id, 'new-portal'); assert.equal(created.repository, 'acme/portal'); assert.equal(created.github_installation, 42);
   assert.equal(created.branch, 'main'); assert.equal(created.domain, 'new.example.com'); assert.equal(created.server_id, 'local');
   assert.equal(created.auto_deploy, true); assert.equal(created.customer_hosts, true);
   assert.deepEqual(created.database, { mode: 'external', url: 'postgres://fixture.example/db?sslmode=require', backup: { hours: 24, keep: 9, offsite: true } });
   assert.deepEqual(created.env, { MAIL_API_KEY: 'fixture-only-secret' }); assert.deepEqual(created.env_kinds, { MAIL_API_KEY: 'credential' });
   await go(page, 'page/settings/portal');
   await page.getByRole('tab', { name: 'Environment', exact: true }).click();
   assert.equal(await page.getByRole('tabpanel', { name: 'Environment', exact: true }).isVisible(), true);
   const setting = page.locator('.env-row').filter({ has: page.locator('input[value=LOG_LEVEL]') });
   const credential = page.locator('.env-row').filter({ has: page.locator('input[value=API_TOKEN]') });
   const plainRect = await setting.locator('.env-value').boundingBox(), secretRect = await credential.locator('.env-value').boundingBox();
   assert.equal(plainRect.height, secretRect.height, 'Credential height diverges from plain input');
   const eyeRect = await credential.locator('.env-reveal').boundingBox();
   assert(Math.abs(eyeRect.y + eyeRect.height / 2 - secretRect.y - secretRect.height / 2) < 2, 'Credential eye is not centered');
   assert.equal(await credential.locator('.env-value').inputValue(), '');
   await credential.locator('.env-reveal').click();
   const factor = page.getByRole('alertdialog', { name: 'Verify to reveal credential' });
   await factor.getByRole('textbox').fill('123456'); await factor.getByRole('button', { name: 'Verify & reveal' }).click();
   await page.waitForFunction(() => document.querySelector('input[value="fixture-secret-value"]'));
   await setting.locator('.env-value').fill('debug');
   await page.getByRole('button', { name: 'Save changes' }).click();
   await page.waitForURL(url => url.hash === '#applications');
   const saved = state.calls.find(c => c.path.endsWith('/portal/settings') && c.method === 'PATCH').body;
   assert.equal(saved.domain, 'portal.example.com'); assert.equal(saved.branch, 'main');
   assert.equal(saved.env_changes.LOG_LEVEL, 'debug'); assert.equal(saved.env_changes.API_TOKEN, undefined, 'Revealed secret was accidentally replaced');
   await go(page, 'page/console/local');
   assert.equal(await page.getByRole('button', { name: 'Run command' }).isDisabled(), true);
   await page.locator('#console-unlock input').fill('654321');
   await page.getByRole('button', { name: 'Unlock for 15 minutes' }).click();
   await page.getByRole('button', { name: 'Extend access' }).waitFor();
   assert.equal(await page.locator('#console-unlock input').inputValue(), '');
   await page.locator('#console-command textarea').fill('docker ps');
   await page.getByRole('button', { name: 'Run command' }).click();
   assert.equal(await page.locator('#console-command textarea').inputValue(), '');
   await page.getByText('rows: 2', { exact: false }).waitFor();
   await page.getByRole('button', { name: 'Copy output' }).click();
   assert.match(await page.evaluate(() => window.consoleCopied), /rows: 2[\s\S]*exit 0/);
   assert(state.calls.some(c => c.body?.purpose === 'credential.reveal' && c.body?.target === 'portal/API_TOKEN'));
   assert(state.calls.some(c => c.body?.purpose === 'server.console' && c.body?.target === 'local'));
   await go(page, 'page/database/portal');
   await page.getByRole('button', { name: 'Restore', exact: true }).click();
   const restore = page.getByRole('alertdialog', { name: 'Restore backup into a new database' });
   await restore.getByRole('textbox').fill('restored-portal');
   await restore.getByRole('button', { name: 'Start restore' }).click();
   await restore.waitFor({ state: 'hidden' });
   assert(state.calls.some(c => c.path.endsWith('/portal/restore') && c.body.target === 'restored-portal'));
   await go(page, 'page/containers/local');
   await page.getByRole('button', { name: 'Restart', exact: true }).click();
   const restart = page.getByRole('alertdialog'); await restart.getByRole('button', { name: 'Restart container' }).click();
   await restart.waitFor({ state: 'hidden' });
   assert(state.calls.some(c => c.path.endsWith('/containers/restart') && c.body.name.startsWith('lidza-portal-')));
   await go(page, 'help');
   await page.getByRole('button', { name: 'Open example dialog' }).click();
   await page.getByRole('dialog', { name: 'A focused conversation' }).waitFor(); await page.keyboard.press('Escape');
   await page.getByRole('dialog', { name: 'A focused conversation' }).waitFor({ state: 'hidden' });
   await page.getByRole('button', { name: 'Open example panel' }).click();
   await page.getByRole('dialog', { name: 'Room for the details' }).waitFor(); await page.keyboard.press('Escape');
   await page.getByRole('dialog', { name: 'Room for the details' }).waitFor({ state: 'hidden' });
   await page.getByRole('button', { name: 'Primary action' }).click();
   await page.getByText('Example action completed.').waitFor();
   await go(page, 'page/two-factor/account');
   await page.getByRole('button', { name: 'Set up authenticator' }).click();
   await page.getByRole('img', { name: 'QR code for Līdza Deploy two-factor setup' }).waitFor();
   assert.deepEqual(errors, []);
   await page.close(); console.log(`PASS: wizard payload, MFA credential reveal/save, JIT root console, clipboard, safe restore/restart, gallery and QR setup at ${width}px`);
  }
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
